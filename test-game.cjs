const { chromium } = require('playwright');
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=swiftshader','--enable-webgl'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  const errors = [];
  page.on('console', (msg) => { if (msg.type() === 'error') errors.push('CONSOLE: ' + msg.text()); });
  page.on('pageerror', (err) => errors.push('PAGEERROR: ' + err.message));
  await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle', timeout: 60000 });
  await page.waitForTimeout(1200);
  console.log('TITLE:', await page.title());
  console.log('H1:', (await page.locator('h1').first().innerText()).replace(/\n/g, ' | '));
  await page.screenshot({ path: '/tmp/home.png' });
  await page.getByRole('button', { name: /Jugar ahora/i }).first().click();
  await page.waitForTimeout(700);
  await page.screenshot({ path: '/tmp/prerace.png' });
  console.log('PRERACE:', (await page.locator('h1').first().innerText()).replace(/\n/g, ' | '));
  await page.getByRole('button', { name: /Entrar a la parrilla/i }).click();
  await page.waitForTimeout(4500);
  await page.screenshot({ path: '/tmp/race-start.png' });
  await page.keyboard.down('ArrowUp');
  await page.waitForTimeout(2500);
  await page.keyboard.down('ArrowLeft');
  await page.waitForTimeout(700);
  await page.keyboard.up('ArrowLeft');
  await page.keyboard.down('ShiftLeft');
  await page.waitForTimeout(1100);
  await page.keyboard.up('ShiftLeft');
  await page.waitForTimeout(2500);
  await page.screenshot({ path: '/tmp/race-run.png' });
  await page.keyboard.up('ArrowUp');
  const rootText = await page.locator('.race-root').innerText();
  console.log('RACE TEXT SAMPLE:', rootText.slice(0, 600).replace(/\n/g, ' | '));
  console.log('ERRORS:', errors.length ? errors.join('\n') : 'none');
  await browser.close();
})().catch(e => { console.error('FAILED', e); process.exit(1); });
